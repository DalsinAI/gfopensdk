#!/usr/bin/env python3
"""Makes the Open SDK's AROS compatibility headers that are long and
regular: aros/asmcall.h (AROS_UFHn, AROS_UFPn, AROS_UFCn), aros/libcall.h
(AROS_LHn, AROS_LDn, AROS_LPn, AROS_LCn, AROS_CALLn) and
aros/shcommands.h (AROS_SHn, AROS_SHnH), for 0 to MAX arguments. Written
by the Team from the macros' published use in AROS programs (their names
and arguments are the interface); nothing of AROS's own headers.
MIT, Copyright (c) 2026 AmiCradle Team.
  python3 tools/gen_aroscompat.py [--check]"""
import os, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "Include", "aroscompat", "aros")
MAX = 16
BANNER = ("/* Generated by tools/gen_aroscompat.py: do not edit. The Open SDK's AROS\n"
          " * compatibility (Docs/PORTING-AROS.md). MIT, Copyright (c) 2026 AmiCradle Team. */\n")

def args(n, f): return ", ".join(f(i) for i in range(1, n + 1))

def asmcall():
    o = [BANNER, "#ifndef AROS_ASMCALL_H", "#define AROS_ASMCALL_H", "",
         "#include <aros/aroscompat_regs.h>", "",
         "/* a hook or callback: its arguments in the registers the caller loads",
         " * (AROS_UFHA(type, name, A0)); the body's INIT and EXIT do nothing here */",
         "#define AROS_UFHA(type, name, reg) register type name __asm(__AC_REG(reg))",
         "#define AROS_UFPA(type, name, reg) register type name __asm(__AC_REG(reg))",
         "#define AROS_UFCA(type, value, reg) (type, value, reg)",
         "#define AROS_USERFUNC_INIT",
         "#define AROS_USERFUNC_EXIT",
         "/* a process's entry: its argument string and length, and SysBase */",
         "#define AROS_PROCH(name, argstr, argsize, sysbase) \\",
         "    ULONG name(register STRPTR argstr __asm(\"a0\"), register ULONG argsize __asm(\"d0\"), \\",
         "               register struct ExecBase *sysbase __asm(\"a6\"))",
         "#define AROS_PROCP(name) ULONG name(register STRPTR __asm(\"a0\"), register ULONG __asm(\"d0\"), \\",
         "               register struct ExecBase * __asm(\"a6\"))",
         "#define AROS_PROCFUNC_INIT",
         "#define AROS_PROCFUNC_EXIT",
         "struct ExecBase;", ""]
    for n in range(0, MAX + 1):
        a = args(n, lambda i: "a%d" % i)
        p = ", " + a if n else ""
        plist = a if n else "void"
        o.append("#define AROS_UFH%d(t, name%s) t name(%s)" % (n, p, plist))
        o.append("#define AROS_UFH%dS(t, name%s) static t name(%s)" % (n, p, plist))
        o.append("#define AROS_UFP%d(t, name%s) t name(%s)" % (n, p, plist))
        o.append("#define AROS_UFP%dS(t, name%s) static t name(%s)" % (n, p, plist))
        decl = args(n, lambda i: "__AC_D a%d" % i) if n else "void"
        vals = args(n, lambda i: "__AC_V a%d" % i)
        o.append("#define AROS_UFC%d(t, f%s) (((t (*)(%s))(void *)(f))(%s))" % (n, p, decl, vals))
    o += ["", "#endif", ""]
    return "\n".join(o)

def libcall():
    o = [BANNER, "#ifndef AROS_LIBCALL_H", "#define AROS_LIBCALL_H", "",
         "#include <aros/aroscompat_regs.h>", "",
         "/* a library function: its arguments in registers, the base in A6.",
         " * AROS_LH2(t, name, AROS_LHA(...), AROS_LHA(...), btype, base, offset, lib)",
         " * defines lib_name(); AROS_SLIB_ENTRY(name, lib, offset) is that name;",
         " * AROS_LCn calls a library's function by its offset (LVO -6 * offset) */",
         "#define AROS_LHA(type, name, reg) register type name __asm(__AC_REG(reg))",
         "#define AROS_LPA(type, name, reg) register type name __asm(__AC_REG(reg))",
         "#define AROS_LDA(type, name, reg) register type name __asm(__AC_REG(reg))",
         "#define AROS_LCA(type, value, reg) (type, value, reg)",
         "#define AROS_LIBFUNC_INIT",
         "#define AROS_LIBFUNC_EXIT",
         "#define AROS_SLIB_ENTRY(name, lib, offset) lib##_##name",
         "#define __AC_LVO(base, offset) ((void *)((char *)(base) - 6 * (offset)))", ""]
    for n in range(0, MAX + 1):
        a = args(n, lambda i: "a%d" % i)
        p = ", " + a if n else ""
        plist = (a + ", ") if n else ""
        o.append("#define AROS_LH%d(t, name%s, bt, bn, offset, lib) t lib##_##name(%sregister bt bn __asm(\"a6\"))" % (n, p, plist))
        o.append("#define AROS_LH%dI(t, name%s, bt, bn, offset, lib) t lib##_##name(%sregister bt bn __asm(\"a6\"))" % (n, p, plist))
        o.append("#define AROS_LD%d(t, name%s, bt, bn, offset, lib) t lib##_##name(%sregister bt bn __asm(\"a6\"))" % (n, p, plist))
        o.append("#define AROS_LP%d(t, name%s, bt, bn, offset, lib) t lib##_##name(%sregister bt bn __asm(\"a6\"))" % (n, p, plist))
        decl = (args(n, lambda i: "__AC_D a%d" % i) + ", ") if n else ""
        vals = (args(n, lambda i: "__AC_V a%d" % i) + ", ") if n else ""
        o.append("#define AROS_LC%d(t, name%s, bt, bn, offset, lib) (((t (*)(%sregister bt __asm(\"a6\")))__AC_LVO((bn), (offset)))(%s(bn)))" % (n, p, decl, vals))
        o.append("#define AROS_LC%dNR(t, name%s, bt, bn, offset, lib) ((void)AROS_LC%d(t, name%s, bt, bn, offset, lib))" % (n, p, n, p))
        o.append("#define AROS_CALL%d(t, f%s, bt, bn) (((t (*)(%sregister bt __asm(\"a6\")))(void *)(f))(%s(bn)))" % (n, p, decl, vals))
        o.append("#define AROS_CALL%dNR(t, f%s, bt, bn) ((void)AROS_CALL%d(t, f%s, bt, bn))" % (n, p, n, p))
    o += ["", "#endif", ""]
    return "\n".join(o)

def shcommands():
    o = [BANNER, "#ifndef AROS_SHCOMMANDS_H", "#define AROS_SHCOMMANDS_H", "",
         "/* A Shell command in AROS's form:",
         " *   AROS_SH2(Name, 41.1,",
         " *   AROS_SHA(STRPTR, ,FILE,/A,NULL),",
         " *   AROS_SHA(BOOL, Q=,QUIET,/S,FALSE))",
         " *   { AROS_SHCOMMAND_INIT ... SHArg(FILE) ... return RETURN_OK; AROS_SHCOMMAND_EXIT }",
         " * becomes main(): the template from the arguments (\"FILE/A,Q=QUIET/S\"),",
         " * their defaults, ReadArgs (aroscompat_shmain, Lib/aroscompat), then the",
         " * body with SHArg(name) as the argument's value in its own type. */",
         "#include <exec/types.h>",
         "#include <dos/dos.h>", "",
         "struct ExecBase; struct DosLibrary;",
         "/* the body has SysBase and DOSBase of its own, as AROS's does, for",
         " * programs built with __NOLIBBASE__ */",
         "typedef ULONG (*aroscompat_shbody)(IPTR *__shargs, struct ExecBase *SysBase, struct DosLibrary *DOSBase);",
         "int aroscompat_shmain(const char *name, const char *tmpl, const char *help,",
         "                      const IPTR *defaults, ULONG n, aroscompat_shbody body);", "",
         "#define AROS_SHA(type, abbr, name, mod, def) (type, abbr, name, mod, def, \"\")",
         "#define AROS_SHAH(type, abbr, name, mod, def, help) (type, abbr, name, mod, def, help)",
         "#define __SH_TYPE(t, a, n, m, d, h) typedef t __sht_##n;",
         "#define __SH_IDX(t, a, n, m, d, h) __shi_##n,",
         "#define __SH_TPL(t, a, n, m, d, h) #a #n #m",
         "#define __SH_DEF(t, a, n, m, d, h) (IPTR)(d),",
         "#define __SH_HELP(t, a, n, m, d, h) h",
         "#define SHArg(n) ((__sht_##n)__shargs[__shi_##n])",
         "#define SHArgs __shargs",
         "#define AROS_SHCOMMAND_INIT",
         "#define AROS_SHCOMMAND_EXIT",
         "#define __SH_START(name, version, help, tpl, n) \\",
         "    static const char __sh_version[] __attribute__((used)) = \"$VER: \" #name \" \" #version; \\",
         "    static ULONG __sh_body(IPTR *__shargs, struct ExecBase *SysBase, struct DosLibrary *DOSBase); \\",
         "    int main(void) { return aroscompat_shmain(#name, tpl, help, __sh_defaults, n, __sh_body); } \\",
         "    static ULONG __sh_body(IPTR *__shargs, struct ExecBase *SysBase, struct DosLibrary *DOSBase)", ""]
    for n in range(0, MAX + 1):
        a = args(n, lambda i: "a%d" % i)
        p = ", " + a if n else ""
        types = " ".join("__SH_TYPE a%d" % i for i in range(1, n + 1))
        idx = " ".join("__SH_IDX a%d" % i for i in range(1, n + 1))
        tpl = ' ","  '.join("__SH_TPL a%d" % i for i in range(1, n + 1)) or '""'
        helps = " ".join("__SH_HELP a%d" % i for i in range(1, n + 1))
        defs = " ".join("__SH_DEF a%d" % i for i in range(1, n + 1)) or "0"
        for h in (False, True):
            hp = ", help" if h else ""
            hstr = ("help " + helps) if h else ('"" ' + helps if n else '""')
            o.append("#define AROS_SH%d%s(name, version%s%s) \\" % (n, "H" if h else "", hp, p))
            o.append("    %s enum { %s __sh_n_ }; \\" % (types, idx))
            o.append("    static const IPTR __sh_defaults[] = { %s }; \\" % defs)
            o.append("    __SH_START(name, version, %s, %s, %d)" % (hstr, tpl, n))
    o += ["", "#endif", ""]
    return "\n".join(o)

def regs():
    o = [BANNER, "#ifndef AROS_AROSCOMPAT_REGS_H", "#define AROS_AROSCOMPAT_REGS_H", "",
         "/* AROS names registers D0..A6; GCC's m68k wants d0..a6 */",
         "#define __AC_REG(r) __AC_REG_##r"]
    for r in ["D%d" % i for i in range(8)] + ["A%d" % i for i in range(7)]:
        o.append("#define __AC_REG_%s \"%s\"" % (r, r.lower()))
    o += ["/* (type, value, reg): a parameter of a function pointer's type, and the value */",
          "#define __AC_D(t, v, r) register t __asm(__AC_REG(r))",
          "#define __AC_V(t, v, r) (v)", "", "#endif", ""]
    return "\n".join(o)

def main():
    out = {"asmcall.h": asmcall(), "libcall.h": libcall(), "shcommands.h": shcommands(),
           "aroscompat_regs.h": regs()}
    check = "--check" in sys.argv
    bad = 0
    for name, text in out.items():
        p = os.path.join(OUT, name)
        if check:
            if not os.path.exists(p) or open(p).read() != text:
                print("out of date: Include/aroscompat/aros/" + name); bad = 1
        else:
            os.makedirs(OUT, exist_ok=True)
            open(p, "w").write(text)
    sys.exit(bad)

main()
